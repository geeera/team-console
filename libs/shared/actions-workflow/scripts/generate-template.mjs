// Writes src/lib/template.generated.ts from apps/runner/templates/team-console-runner.yml (#759), so the api Worker
// bundles the reviewed template as a plain string, with no file loader or text-module rule in any toolchain. Rerun
// after every template change:
//   node libs/shared/actions-workflow/scripts/generate-template.mjs
// src/lib/template.spec.ts fails until the generated string equals the file byte for byte again.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../..');
const template = readFileSync(join(root, 'apps/runner/templates/team-console-runner.yml'), 'utf8');

const source = `// Generated by libs/shared/actions-workflow/scripts/generate-template.mjs from
// apps/runner/templates/team-console-runner.yml. Do not edit by hand: change the template and rerun the script
// (template.spec.ts keeps the two equal).

export const RUNNER_WORKFLOW_TEMPLATE = ${JSON.stringify(template)};
`;

writeFileSync(join(here, '../src/lib/template.generated.ts'), source);
