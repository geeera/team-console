import { LABEL_COLOR_PATTERN, LABEL_NAME_PATTERN } from '@shared/contracts';
import seed from './labels-seed.json';

/** One builtin label of a project's tracker. */
export interface LabelSeed {
  readonly name: string;
  readonly color: string;
  readonly description: string;
}

function parseSeed(rows: readonly (readonly unknown[])[]): readonly LabelSeed[] {
  return rows.map((row) => {
    const [name, color, description] = row;
    if (
      row.length !== 3 ||
      typeof name !== 'string' ||
      !LABEL_NAME_PATTERN.test(name) ||
      typeof color !== 'string' ||
      !LABEL_COLOR_PATTERN.test(color) ||
      typeof description !== 'string'
    ) {
      throw new Error(`labels-seed.json holds a malformed row: ${JSON.stringify(row)}`);
    }
    return { name, color, description };
  });
}

/**
 * The plugin's `ptlib/labels.py` `LABELS`, in its order: what a project's `labels` table starts with when its tracker
 * leaves GitHub (ADR 0006 decision 3). Generated by `scripts/generate-labels-seed.py` from the vendored plugin; the
 * spec fails until the file is regenerated after a `vendor` update.
 */
export const LABELS_SEED: readonly LabelSeed[] = parseSeed(seed.labels);
